const CURL_BIN: &str = "/usr/bin/curl";

/// Fetch the appcast document over HTTPS. Refuses (without spawning
/// `curl` at all) if `url` is not `https://`. Redirects are followed but
/// locked to `https://` too (`--proto-redir '=https'`), so a compromised
/// or misconfigured server can't downgrade the connection mid-request.
pub fn fetch_appcast_text(url: &str) -> Result<String, UpdateError> {
    require_https(url)?;
    let output = Command::new(CURL_BIN)
        .args([
            "--fail",
            "--silent",
            "--show-error",
            "--location",
            "--proto",
            "=https",
            "--proto-redir",
            "=https",
            "--max-time",
            "30",
        ])
        .arg(url)
        .output()
        .map_err(|e| UpdateError::Http(format!("failed to run {CURL_BIN}: {e}")))?;
    if !output.status.success() {
        return Err(UpdateError::Http(format!(
            "curl exited with {}: {}",
            output.status,
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }
    String::from_utf8(output.stdout)
        .map_err(|e| UpdateError::Http(format!("appcast response was not valid UTF-8: {e}")))
}

pub fn check_for_update(appcast_url: &str, current: &Version) -> Result<CheckResult, UpdateError> {
    let text = fetch_appcast_text(appcast_url)?;
    evaluate_appcast(&text, current)
}

/// Progress callback: `(bytes_downloaded_so_far, total_bytes_if_known)`,
/// same shape as `voice_asr_whisper::model::ProgressCallback`.
/// `total_bytes_if_known` is `0` when it can't be determined up front.
pub type ProgressCallback<'a> = dyn FnMut(u64, u64) + 'a;

/// Download `url` to `dest` over HTTPS via `curl`, polling `dest`'s size
/// on a short interval to drive `progress` (curl writes straight to
/// `dest`, so the file's size on disk *is* the download progress -- no
/// need to parse curl's own progress-meter output). `total` comes from
/// `item.length` when the caller has it (see [`download_and_verify`]).
fn download_to_file(
    url: &str,
    dest: &Path,
    total: u64,
    mut progress: Option<&mut ProgressCallback<'_>>,
) -> Result<(), UpdateError> {
    require_https(url)?;
    let mut child = Command::new(CURL_BIN)
        .args([
            "--fail",
            "--silent",
            "--show-error",
            "--location",
            "--proto",
            "=https",
            "--proto-redir",
            "=https",
            "--max-time",
            "600",
            "--output",
        ])
        .arg(dest)
        .arg(url)
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .spawn()
        .map_err(|e| UpdateError::Http(format!("failed to run {CURL_BIN}: {e}")))?;

    loop {
        match child.try_wait() {
            Ok(Some(status)) => {
                if let Some(cb) = progress.as_deref_mut() {
                    let size = fs::metadata(dest).map(|m| m.len()).unwrap_or(0);
                    cb(size, total);
                }
                if status.success() {
                    return Ok(());
                }
                let mut stderr = String::new();
                if let Some(mut s) = child.stderr.take() {
                    use io::Read as _;
                    let _ = s.read_to_string(&mut stderr);
                }
                return Err(UpdateError::Http(format!(
                    "curl exited with {status}: {}",
                    stderr.trim()
                )));
            }
            Ok(None) => {
                if let Some(cb) = progress.as_deref_mut() {
                    let size = fs::metadata(dest).map(|m| m.len()).unwrap_or(0);
                    cb(size, total);
                }
                std::thread::sleep(Duration::from_millis(150));
            }
            Err(e) => return Err(UpdateError::Http(format!("failed to poll curl: {e}"))),
        }
    }
}

/// The whole verified-download pipeline: download to a `.partial` temp
/// file inside `staging_dir`, check its size against
/// `item.length`, verify its ed25519 signature, and **only on success**
/// rename it into a `.verified` path. On any failure (network, length
/// mismatch, bad signature) the temp file is deleted and `Err` is
/// returned -- there is no code path that leaves an unverified file
/// behind under a name anything else would trust. See this module's doc
/// comment, point 2, and [`ensure_not_downgrade`] for the second
/// downgrade guard this also runs.
pub fn download_and_verify(
    item: &AppcastItem,
    current: &Version,
    verifier: &Verifier,
    staging_dir: &Path,
    progress: Option<&mut ProgressCallback<'_>>,
) -> Result<PathBuf, UpdateError> {
    let candidate = item.parsed_version()?;
    ensure_not_downgrade(current, &candidate)?;
    require_https(&item.url)?;
    let signature = decode_hex_fixed_64(&item.signature, "appcast item signature")?;

    fs::create_dir_all(staging_dir)?;
    let tmp = staging_dir.join(format!("update-{}.download.partial", item.version));
    // Best-effort: an interrupted previous attempt may have left a stale
    // partial file; a fresh download must start clean.
    let _ = fs::remove_file(&tmp);

    download_to_file(&item.url, &tmp, item.length, progress)?;

    let actual_len = fs::metadata(&tmp)?.len();
    if actual_len != item.length {
        let _ = fs::remove_file(&tmp);
        return Err(UpdateError::LengthMismatch {
            expected: item.length,
            actual: actual_len,
        });
    }

    // Signature verification needs the whole message in memory (ring's
    // `verify` takes `&[u8]`, not a stream) -- fine for an app-bundle-
    // sized payload (tens of MB), read once here rather than kept
    // resident for the whole download.
    let bytes = fs::read(&tmp)?;
    if let Err(e) = verifier.verify(&bytes, &signature) {
        // CRITICAL: delete rather than leave around under any name --
        // an unverified file must never be reachable by a later "trust
        // whatever's already staged" code path.
        let _ = fs::remove_file(&tmp);
        return Err(e);
    }

    let verified_path = staging_dir.join(format!("update-{}.verified.zip", item.version));
    let _ = fs::remove_file(&verified_path);
    fs::rename(&tmp, &verified_path)?;
    Ok(verified_path)
}


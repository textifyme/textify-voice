    /// Real, end-to-end execution of the generated swap script against
    /// synthetic bundle-shaped directories (not the actual live signed
    /// app -- see this unit's report for what could not be verified).
    /// Spawns a genuine short-lived child process and uses its real PID
    /// as `wait_pid`, so the script's `kill -0` polling loop is exercised
    /// for real, not mocked.
    #[test]
    fn relaunch_script_swaps_atomically_after_parent_exits() {
        let dir = temp_dir("swap-real");
        let installed = dir.join("Installed.app");
        let staged = dir.join("Staged.app");
        fs::create_dir_all(&installed).unwrap();
        fs::write(installed.join("marker.txt"), "old").unwrap();
        fs::create_dir_all(&staged).unwrap();
        fs::write(staged.join("marker.txt"), "new").unwrap();

        let marker_path = dir.join("relaunched.marker");
        let relaunch_cmd = format!("touch {}", shell_quote(&marker_path.to_string_lossy()));

        // A real short-lived process standing in for "the running app
        // that must exit before the swap can happen". Reaped from a
        // background thread the moment it exits (rather than after the
        // helper script finishes) so it does not sit around as a zombie
        // for the whole poll loop below: a zombie's PID stays visible to
        // `kill -0` from *any* process until its own parent reaps it, and
        // this test process is that parent (`Command::spawn` makes it
        // so). In the real production flow there is no such window --
        // the app process the swap script waits on is not a child of
        // anything that would delay reaping it.
        let mut dummy_parent = Command::new("/bin/sleep").arg("1").spawn().unwrap();
        let pid = dummy_parent.id();
        let reaper = std::thread::spawn(move || {
            let _ = dummy_parent.wait();
        });

        let script = build_relaunch_script(pid, &installed, &staged, &relaunch_cmd);
        let script_path = dir.join("relaunch.sh");
        fs::write(&script_path, &script).unwrap();

        let mut helper = Command::new("/bin/sh").arg(&script_path).spawn().unwrap();
        let status = helper.wait().unwrap();
        reaper.join().unwrap();

        assert!(status.success(), "relaunch script exited non-zero");
        assert_eq!(
            fs::read_to_string(installed.join("marker.txt")).unwrap(),
            "new",
            "installed app was not swapped for the staged one"
        );
        assert!(!staged.exists(), "staged dir should have been moved, not copied");
        assert!(
            !dir.join("Installed.app.update-backup").exists(),
            "backup should be cleaned up after a successful swap"
        );
        assert!(marker_path.exists(), "relaunch command did not run");
    }

    /// The other half of "nothing is destroyed until verified and
    /// staged": if the move-in step itself fails, the script must put the
    /// original back rather than leave the user with neither app.
    #[test]
    fn relaunch_script_restores_backup_if_move_in_fails() {
        let dir = temp_dir("swap-restore");
        let installed = dir.join("Installed.app");
        fs::create_dir_all(&installed).unwrap();
        fs::write(installed.join("marker.txt"), "old").unwrap();
        // Deliberately do NOT create the staged path -- `mv` on a
        // nonexistent source fails, simulating "the move-in step failed".
        let staged = dir.join("DoesNotExist.app");

        let mut dummy_parent = Command::new("/bin/sleep").arg("0.2").spawn().unwrap();
        let pid = dummy_parent.id();
        let reaper = std::thread::spawn(move || {
            let _ = dummy_parent.wait();
        });

        let script = build_relaunch_script(pid, &installed, &staged, "true");
        let script_path = dir.join("relaunch.sh");
        fs::write(&script_path, &script).unwrap();

        let mut helper = Command::new("/bin/sh").arg(&script_path).spawn().unwrap();
        let status = helper.wait().unwrap();
        reaper.join().unwrap();

        assert!(!status.success(), "script should report failure");
        assert_eq!(
            fs::read_to_string(installed.join("marker.txt")).unwrap(),
            "old",
            "the original app must still be in place after a failed swap"
        );
    }


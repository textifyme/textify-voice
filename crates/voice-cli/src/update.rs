#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AppcastItem {
    /// `"major.minor.patch"`.
    pub version: String,
    /// Where to download the payload from. Must be `https://` (checked by
    /// [`parse_appcast`] at parse time, and again by
    /// [`download_and_verify`] before it downloads anything).
    pub url: String,
    /// Detached ed25519 signature over the exact bytes at `url`, as 128
    /// lower-case hex characters (64 raw bytes).
    pub signature: String,
    /// Exact expected byte length of the payload at `url`. Checked before
    /// signature verification is attempted, purely as a cheap early exit
    /// on an obviously truncated download -- the signature check is what
    /// actually matters and runs regardless.
    pub length: u64,
    #[serde(default)]
    pub notes: Option<String>,
    #[serde(default)]
    pub pub_date: Option<String>,
}

impl AppcastItem {
    fn parsed_version(&self) -> Result<Version, UpdateError> {
        Version::parse(&self.version)
    }
}

#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct Appcast {
    pub items: Vec<AppcastItem>,
}

/// Parse and structurally validate an appcast JSON document. Every field
/// that later code trusts without re-checking is validated right here, so
/// "malformed appcast" is one well-defined error path
/// ([`UpdateError::MalformedAppcast`] / [`UpdateError::BadVersion`] /
/// [`UpdateError::InsecureUrl`] / [`UpdateError::BadHexEncoding`]), not a
/// panic or a silently-wrong `CheckResult` three functions later:
///
/// - valid JSON matching the [`Appcast`] shape
/// - at least one item
/// - every item's `url` is `https://`
/// - every item's `version` parses as [`Version`]
/// - every item's `signature` is exactly 128 hex characters (64 bytes)
pub fn parse_appcast(json: &str) -> Result<Appcast, UpdateError> {
    let appcast: Appcast =
        serde_json::from_str(json).map_err(|e| UpdateError::MalformedAppcast(e.to_string()))?;
    if appcast.items.is_empty() {
        return Err(UpdateError::MalformedAppcast(
            "appcast has no items".to_string(),
        ));
    }
    for item in &appcast.items {
        require_https(&item.url)?;
        item.parsed_version()?;
        decode_hex_fixed_64(&item.signature, "appcast item signature")?;
    }
    Ok(appcast)
}

/// The item with the highest [`Version`] in an already-[`parse_appcast`]-validated
/// appcast. `Err` only if `items` is empty, which [`parse_appcast`] never
/// produces -- kept fallible (rather than panicking on `.max_by_key`'s
/// `None`) so a caller building an [`Appcast`] by hand (e.g. a future
/// test or tool) can't trigger a panic.
pub fn latest_item(appcast: &Appcast) -> Result<&AppcastItem, UpdateError> {
    let mut best: Option<(Version, &AppcastItem)> = None;
    for item in &appcast.items {
        let v = item.parsed_version()?;
        if best.as_ref().is_none_or(|(bv, _)| v > *bv) {
            best = Some((v, item));
        }
    }
    best.map(|(_, item)| item).ok_or_else(|| {
        UpdateError::MalformedAppcast("appcast has no items".to_string())
    })
}

#[derive(Debug, Clone, PartialEq)]
pub enum CheckResult {
    UpToDate,
    Available(AppcastItem),
}

/// The pure, network-free half of a check: given appcast JSON text
/// already in hand (fetched by [`fetch_appcast_text`], read from a local
/// fixture file, whatever) and the running version, decide whether an
/// update is available. See this module's doc comment, point 4, for the
/// downgrade-prevention property this establishes.
pub fn evaluate_appcast(json: &str, current: &Version) -> Result<CheckResult, UpdateError> {
    let appcast = parse_appcast(json)?;
    let item = latest_item(&appcast)?;
    let candidate = item.parsed_version()?;
    if candidate > *current {
        Ok(CheckResult::Available(item.clone()))
    } else {
        Ok(CheckResult::UpToDate)
    }
}


// Hex encode/decode (no new dependency -- see module doc comment)
// ---------------------------------------------------------------------

/// Test-only helper (round-tripping [`decode_hex`] in tests, and printing
/// generated test keys) -- nothing in the production code paths below
/// needs to *encode* hex; they only ever decode a signature/public key
/// that arrived as hex (from [`PUBLIC_KEY_HEX`] or an appcast item).
#[cfg(test)]
fn encode_hex(bytes: &[u8]) -> String {
    use std::fmt::Write as _;
    bytes.iter().fold(String::with_capacity(bytes.len() * 2), |mut acc, b| {
        let _ = write!(acc, "{b:02x}");
        acc
    })
}

fn hex_val(c: u8) -> Option<u8> {
    match c {
        b'0'..=b'9' => Some(c - b'0'),
        b'a'..=b'f' => Some(c - b'a' + 10),
        b'A'..=b'F' => Some(c - b'A' + 10),
        _ => None,
    }
}

fn decode_hex(s: &str) -> Result<Vec<u8>, UpdateError> {
    let s = s.trim();
    if s.len() % 2 != 0 {
        return Err(UpdateError::BadHexEncoding(format!(
            "odd-length hex string ({} chars)",
            s.len()
        )));
    }
    let bytes = s.as_bytes();
    let mut out = Vec::with_capacity(bytes.len() / 2);
    for pair in bytes.chunks_exact(2) {
        let hi = hex_val(pair[0])
            .ok_or_else(|| UpdateError::BadHexEncoding(format!("invalid hex character in {s:?}")))?;
        let lo = hex_val(pair[1])
            .ok_or_else(|| UpdateError::BadHexEncoding(format!("invalid hex character in {s:?}")))?;
        out.push((hi << 4) | lo);
    }
    Ok(out)
}

fn decode_hex_fixed_32(s: &str, what: &str) -> Result<[u8; 32], UpdateError> {
    let v = decode_hex(s)?;
    if v.len() != 32 {
        return Err(UpdateError::BadHexEncoding(format!(
            "{what}: expected 32 bytes, got {}",
            v.len()
        )));
    }
    let mut arr = [0u8; 32];
    arr.copy_from_slice(&v);
    Ok(arr)
}

fn decode_hex_fixed_64(s: &str, what: &str) -> Result<[u8; 64], UpdateError> {
    let v = decode_hex(s)?;
    if v.len() != 64 {
        return Err(UpdateError::BadHexEncoding(format!(
            "{what}: expected 64 bytes, got {}",
            v.len()
        )));
    }
    let mut arr = [0u8; 64];
    arr.copy_from_slice(&v);
    Ok(arr)
}


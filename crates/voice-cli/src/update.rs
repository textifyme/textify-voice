//! Auto-update: appcast check, ed25519-verified download, and the macOS
//! stage/swap/relaunch sequence that replaces a running app bundle without
//! ever leaving the user without a working app.
//!
//! # Why this exists (see `packaging/appcast/README.md` for the full design)
//!
//! The app is self-signed (Developer ID enrolment is out of scope for this
//! wave), so macOS code signing gives an update payload zero protection:
//! whoever can serve the appcast can serve any binary. The **update
//! signature verified against a public key compiled into this binary** is
//! therefore the entire real security boundary, independent of TLS
//! (proves "unmodified in transit", not "from the real developer") and
//! independent of code signing (this app has none worth trusting). Every
//! function below is organized around that one fact:
//!
//!   1. [`fetch_appcast_text`] / [`download_and_verify`] refuse anything
//!      that is not `https://` before making a single network call
//!      ([`require_https`]).
//!   2. [`download_and_verify`] verifies the *entire* downloaded payload
//!      against [`AppcastItem::signature`] **before** the bytes are
//!      unpacked, executed, or moved anywhere near the installed app. A
//!      failed verification deletes the temp file and returns `Err` --
//!      nothing downstream ever sees an unverified payload.
//!   3. [`Verifier::from_compiled_in`] reads the public key from
//!      [`PUBLIC_KEY_HEX`], a `const` baked into this binary at compile
//!      time. A key that travelled with the payload would verify nothing
//!      (an attacker serving a fake update could just as easily serve a
//!      fake key), so the verifier never reads a key from the network, the
//!      appcast, or disk.
//!   4. [`evaluate_appcast`] only ever returns [`CheckResult::Available`]
//!      for a version strictly greater than the running one
//!      ([`Version::current`]/[`Version::parse`] + `Ord`), and
//!      [`download_and_verify`] re-checks that itself
//!      ([`ensure_not_downgrade`]) so a caller that skips the check-step
//!      cannot be tricked into a downgrade either.
//!   5. Nothing about the *installed* app is touched until a payload has
//!      cleared step 2 and been staged in a private directory
//!      ([`stage_update`]). The final swap ([`build_relaunch_script`]) is
//!      itself backup-then-atomic-rename, so a crash mid-swap leaves
//!      either the old or the new app intact, never neither.
//!
//! # Why `curl`/`ditto`/`xattr` subprocesses, and the one Rust crate
//!
//! Everything in this file except the signature check itself (appcast
//! parsing, version comparison, downgrade prevention, HTTPS enforcement,
//! staging, the swap script) uses only `voice-cli`'s existing direct
//! dependencies (`serde`, `serde_json`, `dirs`) plus the system tools macOS
//! already ships: `/usr/bin/curl` to download, `/usr/bin/ditto` to unpack,
//! `/usr/bin/xattr` to strip quarantine. `ditto -x -k` in particular is the
//! counterpart of the `ditto -c -k` that produces the payload on the release
//! side (see `packaging/appcast/README.md`), so the archive format has one
//! implementation on both ends rather than two that must agree.
//!
//! The one exception is the ed25519 verification, which calls `ring`'s
//! `UnparsedPublicKey::verify` — there is no safe substitute, and the system
//! openssl/LibreSSL cannot verify ed25519 at all. `ring = "0.17"` is a direct
//! dependency of `voice-cli` and adds no new transitive dependencies
//! (`ring 0.17.14` was already resolved via `ureq`'s rustls feature chain).
//! It was cross-checked against signatures produced by `openssl` — interop
//! with a real signing tool, not just self-consistency, since the signing
//! side lives in `packaging/sign-update.sh` and the two must agree or
//! releases silently fail to verify.
//!
//! # User-visible states
//!
//! [`UpdateState`] is the small, closed set of things a menu-bar item (or
//! any other UI, none of which this unit owns) would show: up to date,
//! available, downloading (with progress), ready to relaunch, or failed
//! (with a message). [`check_now`] and [`spawn_background_checker`] are
//! the two entry points that produce it.


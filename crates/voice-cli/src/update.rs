#[cfg(test)]
mod key_guard {
    #![allow(clippy::unwrap_used, clippy::expect_used)]
    use super::{PLACEHOLDER_PUBLIC_KEY_HEX, PUBLIC_KEY_HEX};

    /// The two halves of the updater have to ship together or not at all: a
    /// build that names an appcast to fetch from must also carry a signing key
    /// somebody can actually sign with, or every update it finds fails
    /// verification and the update path is broken in a way no other test here
    /// would notice.
    ///
    /// So this is keyed off the shipped configuration itself, not an env var
    /// nobody remembers to set: it passes today because
    /// `DEFAULT_UPDATE_APPCAST_URL` is `None` (the placeholder key is safe
    /// precisely because nothing is hosted for it to fail against), and it
    /// starts failing on the commit that configures an appcast while leaving
    /// the throwaway key in place.
    #[test]
    fn a_configured_default_appcast_requires_a_real_signing_key() {
        if crate::dictate::DEFAULT_UPDATE_APPCAST_URL.is_none() {
            return;
        }
        assert_ne!(
            PUBLIC_KEY_HEX, PLACEHOLDER_PUBLIC_KEY_HEX,
            "this build names an appcast to fetch updates from but still carries the throwaway \
             beta signing key, whose private half no longer exists -- every update it downloads \
             would fail signature verification. Run `packaging/sign-update.sh keygen`, store the \
             private key outside the repo, and replace PUBLIC_KEY_HEX with the printed value."
        );
    }
}

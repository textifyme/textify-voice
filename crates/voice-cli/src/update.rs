/// The one check every network-touching function in this module runs
/// first, before any process is spawned. See this module's doc comment,
/// point 1.
pub fn require_https(url: &str) -> Result<(), UpdateError> {
    if url.starts_with("https://") {
        Ok(())
    } else {
        Err(UpdateError::InsecureUrl(url.to_string()))
    }
}


/// A bare `major.minor.patch` version. Deliberately not full semver (no
/// prerelease/build metadata) -- the appcast's job is "is this newer",
/// and three ordered integers answer that unambiguously with an `Ord`
/// derive, which is the only property [`evaluate_appcast`] and
/// [`ensure_not_downgrade`] need.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct Version {
    pub major: u64,
    pub minor: u64,
    pub patch: u64,
}

impl Version {
    /// Parse `"major.minor.patch"`. Rejects anything with a different
    /// number of dot-separated parts, non-numeric parts, or leading/
    /// trailing junk -- an appcast that can't be unambiguously ordered
    /// against the running version must never be silently treated as
    /// "not an update" or "an update"; it must fail loudly
    /// ([`UpdateError::BadVersion`]) as part of "malformed appcast"
    /// handling.
    pub fn parse(s: &str) -> Result<Self, UpdateError> {
        let s = s.trim();
        let parts: Vec<&str> = s.split('.').collect();
        let bad = || UpdateError::BadVersion(s.to_string());
        if parts.len() != 3 {
            return Err(bad());
        }
        let mut nums = [0u64; 3];
        for (i, part) in parts.iter().enumerate() {
            if part.is_empty() || !part.bytes().all(|b| b.is_ascii_digit()) {
                return Err(bad());
            }
            nums[i] = part.parse::<u64>().map_err(|_| bad())?;
        }
        Ok(Version {
            major: nums[0],
            minor: nums[1],
            patch: nums[2],
        })
    }

    /// This build's own version, from `CARGO_PKG_VERSION`
    /// (`[workspace.package].version`, currently `"0.1.0"` -- always a
    /// bare `major.minor.patch`, so the fallback below is unreachable in
    /// practice; it exists so this function never needs `.expect()`
    /// (workspace lint: `clippy::expect_used = "warn"`, which
    /// `-D warnings` turns into a hard error) over a value this module
    /// does not control the source of.
    #[must_use]
    pub fn current() -> Self {
        Self::parse(env!("CARGO_PKG_VERSION")).unwrap_or(Version {
            major: 0,
            minor: 0,
            patch: 0,
        })
    }
}

impl fmt::Display for Version {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}.{}.{}", self.major, self.minor, self.patch)
    }
}

/// Returns `Err` unless `candidate` is strictly newer than `current`. The
/// second, independent enforcement point for downgrade prevention (see
/// this module's doc comment, point 4): [`evaluate_appcast`] already only
/// ever returns [`CheckResult::Available`] for a strictly-newer version,
/// but [`download_and_verify`] calls this itself too, so a caller that
/// builds an [`AppcastItem`] by hand (or replays an old one) cannot skip
/// the check by skipping [`evaluate_appcast`].
pub fn ensure_not_downgrade(current: &Version, candidate: &Version) -> Result<(), UpdateError> {
    if candidate > current {
        Ok(())
    } else {
        Err(UpdateError::Downgrade {
            current: *current,
            candidate: *candidate,
        })
    }
}


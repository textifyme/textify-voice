/// Where staged (already downloaded + verified) updates are unpacked,
/// distinct from the download's own `staging_dir` above only by
/// convention at the call site -- both live under the platform data dir,
/// matching `voice_asr_whisper::model::ModelManager` and
/// `crate::dictionary`'s `~/Library/Application Support/textify/...`
/// convention. `dirs` is already a direct `voice-cli` dependency (used by
/// `dictate.rs`), so this needs no new Cargo.toml entry.
#[must_use]
pub fn default_updates_dir() -> Option<PathBuf> {
    dirs::data_dir().map(|d| d.join("textify").join("updates"))
}

/// The `.app` bundle this process is running from, derived from
/// `current_exe()` by walking up to the nearest ancestor named `*.app`
/// (`.../Foo.app/Contents/MacOS/foo` -> `.../Foo.app`). `None` if this
/// binary is not running from inside a `.app` bundle (e.g. `cargo run`,
/// or a bare CLI invocation) -- there is nothing to swap in that case.
#[must_use]
pub fn current_bundle_root() -> Option<PathBuf> {
    let exe = std::env::current_exe().ok()?;
    exe.ancestors()
        .find(|p| p.extension().is_some_and(|ext| ext == "app"))
        .map(Path::to_path_buf)
}

const DITTO_BIN: &str = "/usr/bin/ditto";
const XATTR_BIN: &str = "/usr/bin/xattr";

/// Unpack a `ditto -c -k`-produced zip (see this module's doc comment for
/// why `ditto`, not `tar`/`zip`) into `dest_dir`, and return the path to
/// the single `.app` bundle it contains. `Err` if the archive doesn't
/// unpack cleanly or doesn't contain exactly one top-level `.app` --
/// either is a payload this code does not understand well enough to
/// trust, not something to guess about.
pub fn unpack_app_zip(archive: &Path, dest_dir: &Path) -> Result<PathBuf, UpdateError> {
    fs::create_dir_all(dest_dir)?;
    let output = Command::new(DITTO_BIN)
        .args(["-x", "-k"])
        .arg(archive)
        .arg(dest_dir)
        .output()
        .map_err(|e| UpdateError::Http(format!("failed to run {DITTO_BIN}: {e}")))?;
    if !output.status.success() {
        return Err(UpdateError::Http(format!(
            "ditto -x -k exited with {}: {}",
            output.status,
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }
    let mut apps = Vec::new();
    for entry in fs::read_dir(dest_dir)? {
        let entry = entry?;
        let path = entry.path();
        if path.extension().is_some_and(|ext| ext == "app") {
            apps.push(path);
        }
    }
    match apps.len() {
        1 => Ok(apps.into_iter().next().unwrap_or(dest_dir.to_path_buf())),
        0 => Err(UpdateError::UnexpectedPayloadLayout(format!(
            "no .app bundle found at the top level of {}",
            dest_dir.display()
        ))),
        n => Err(UpdateError::UnexpectedPayloadLayout(format!(
            "expected exactly one top-level .app bundle, found {n} in {}",
            dest_dir.display()
        ))),
    }
}

/// Strip the quarantine xattr (`com.apple.quarantine`) Gatekeeper stamps
/// on anything downloaded, recursively. `xattr -dr` on a path that has no
/// such attribute anywhere under it is not an error worth failing an
/// install over, so a non-zero exit whose stderr says the attribute is
/// simply absent is tolerated; any other failure is not.
pub fn strip_quarantine(path: &Path) -> Result<(), UpdateError> {
    let output = Command::new(XATTR_BIN)
        .args(["-dr", "com.apple.quarantine"])
        .arg(path)
        .output()
        .map_err(|e| UpdateError::Http(format!("failed to run {XATTR_BIN}: {e}")))?;
    if output.status.success() {
        return Ok(());
    }
    let stderr = String::from_utf8_lossy(&output.stderr);
    if stderr.contains("No such xattr") || stderr.contains("No such file") {
        return Ok(());
    }
    Err(UpdateError::Http(format!(
        "xattr -dr com.apple.quarantine exited with {}: {}",
        output.status,
        stderr.trim()
    )))
}

/// Unpack a verified payload and strip quarantine from it -- everything
/// [`download_and_verify`] leaves for the caller to do before the app is
/// "ready to relaunch". Does **not** touch the installed app; the result
/// lives entirely under `dest_dir` (a fresh subdirectory of
/// [`default_updates_dir`], by convention).
pub fn stage_update(verified_payload_zip: &Path, dest_dir: &Path) -> Result<PathBuf, UpdateError> {
    let app = unpack_app_zip(verified_payload_zip, dest_dir)?;
    strip_quarantine(&app)?;
    Ok(app)
}

/// Shell-single-quote `s` for safe interpolation into the generated swap
/// script: replaces every `'` with `'\''` and wraps the result in `'...'`
/// -- the standard POSIX-shell-safe quoting idiom, correct for any byte
/// sequence including paths with spaces (e.g. `"Textify Voice.app"`).
fn shell_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// The default relaunch command embedded in a generated swap script:
/// `open` the (now-swapped-in) installed app.
#[must_use]
pub fn default_relaunch_cmd(installed_app: &Path) -> String {
    format!("open {}", shell_quote(&installed_app.to_string_lossy()))
}

/// Build the `/bin/sh` script that performs the actual swap, as a
/// **separate process** from this one -- a running app cannot atomically
/// replace its own bundle on disk while it is the process executing out
/// of it (the architectural reason Sparkle ships a standalone
/// `Autoupdate` helper; see this unit's recon). The script:
///
///   1. Polls `kill -0 $PID` until the parent (`wait_pid`) has exited, or
///      gives up after ~2 minutes.
///   2. `mv`s the currently-installed app aside to a backup path (a
///      single `rename(2)` on the same filesystem -- atomic).
///   3. `mv`s the staged app into the installed app's place (same
///      atomicity). If this fails, the backup is moved straight back
///      into place before exiting non-zero -- the installed app is never
///      left half-replaced or absent.
///   4. Re-strips quarantine on the now-installed app (belt and braces;
///      [`stage_update`] already did this once).
///   5. Removes the backup (only reached on success) and runs
///      `relaunch_cmd`.
///
/// Every step after the wait uses `mv`/`rm -rf`/`xattr`, not a
/// higher-level "sync" tool, specifically so each transition is a single
/// filesystem operation this doc comment can reason about atomically.
#[must_use]
pub fn build_relaunch_script(
    wait_pid: u32,
    installed_app: &Path,
    staged_app: &Path,
    relaunch_cmd: &str,
) -> String {
    let installed = shell_quote(&installed_app.to_string_lossy());
    let staged = shell_quote(&staged_app.to_string_lossy());
    format!(
        r#"#!/bin/sh
set -u
PID={wait_pid}
INSTALLED={installed}
STAGED={staged}
BACKUP="$INSTALLED.update-backup"

tries=0
while kill -0 "$PID" 2>/dev/null; do
  sleep 1
  tries=$((tries + 1))
  if [ "$tries" -ge 120 ]; then
    exit 1
  fi
done

rm -rf "$BACKUP"
if ! mv "$INSTALLED" "$BACKUP"; then
  exit 1
fi
if ! mv "$STAGED" "$INSTALLED"; then
  mv "$BACKUP" "$INSTALLED"
  exit 1
fi
{xattr_bin} -dr com.apple.quarantine "$INSTALLED" 2>/dev/null || true
rm -rf "$BACKUP"
{relaunch_cmd}
"#,
        xattr_bin = XATTR_BIN,
    )
}

/// Write `script` to `script_path` (executable) and spawn it detached
/// (`/bin/sh script_path`, stdio nulled) so it keeps running after this
/// process exits. Returns the spawned [`std::process::Child`] --
/// deliberately *not* waited on here; the caller (once this is wired
/// into the running app -- outside this unit's owns-list, see this
/// module's doc comment) is expected to spawn this, then exit the
/// process shortly after, letting the helper perform the swap once this
/// process is gone.
pub fn spawn_relaunch_helper(
    script: &str,
    script_path: &Path,
) -> Result<std::process::Child, UpdateError> {
    fs::write(script_path, script)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(script_path, fs::Permissions::from_mode(0o700))?;
    }
    Command::new("/bin/sh")
        .arg(script_path)
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .spawn()
        .map_err(UpdateError::from)
}


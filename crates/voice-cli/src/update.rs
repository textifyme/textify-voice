#[derive(Debug)]
pub enum UpdateError {
    /// A URL (appcast or payload) did not start with `https://`.
    InsecureUrl(String),
    /// Downloading (via `curl`) or unpacking (via `ditto`) failed.
    Http(String),
    Io(io::Error),
    /// The appcast document was not valid JSON, had no items, or an item
    /// failed one of the structural checks in [`parse_appcast`] (bad
    /// version, non-https url, malformed signature/length).
    MalformedAppcast(String),
    /// A version string was not `major.minor.patch` (three dot-separated
    /// non-negative integers).
    BadVersion(String),
    /// A hex string (public key or signature) was not valid hex, or was
    /// the wrong length for what it's supposed to hold.
    BadHexEncoding(String),
    /// The downloaded payload's size did not match [`AppcastItem::length`].
    LengthMismatch { expected: u64, actual: u64 },
    /// The ed25519 signature did not verify against the compiled-in (or,
    /// in tests, explicitly supplied) public key. This is the one error
    /// variant this entire module exists to be able to return correctly.
    SignatureInvalid,
    /// [`ensure_not_downgrade`] refused to treat an appcast item as
    /// installable because its version is not strictly newer than the
    /// version making the check.
    Downgrade { current: Version, candidate: Version },
    /// Unpacking a staged payload (`ditto -x -k`) did not produce exactly
    /// one `.app` bundle at the top level of the destination directory.
    UnexpectedPayloadLayout(String),
}

impl fmt::Display for UpdateError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            UpdateError::InsecureUrl(url) => {
                write!(f, "refusing a non-https URL: {url}")
            }
            UpdateError::Http(msg) => write!(f, "update network operation failed: {msg}"),
            UpdateError::Io(e) => write!(f, "update I/O error: {e}"),
            UpdateError::MalformedAppcast(msg) => write!(f, "malformed appcast: {msg}"),
            UpdateError::BadVersion(s) => {
                write!(f, "not a valid major.minor.patch version: {s:?}")
            }
            UpdateError::BadHexEncoding(msg) => write!(f, "bad hex encoding: {msg}"),
            UpdateError::LengthMismatch { expected, actual } => write!(
                f,
                "downloaded payload size {actual} bytes does not match the appcast's declared length {expected} bytes; download was likely truncated or corrupted"
            ),
            UpdateError::SignatureInvalid => write!(
                f,
                "update payload signature did not verify against the compiled-in public key -- refusing to install"
            ),
            UpdateError::Downgrade { current, candidate } => write!(
                f,
                "refusing to install {candidate}: it is not newer than the running version {current}"
            ),
            UpdateError::UnexpectedPayloadLayout(msg) => {
                write!(f, "unexpected update payload layout: {msg}")
            }
        }
    }
}

impl std::error::Error for UpdateError {}

impl From<io::Error> for UpdateError {
    fn from(e: io::Error) -> Self {
        UpdateError::Io(e)
    }
}


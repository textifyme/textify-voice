#[derive(Debug, Clone, PartialEq)]
pub enum UpdateState {
    UpToDate,
    Available(AppcastItem),
    Downloading { downloaded: u64, total: u64 },
    ReadyToRelaunch { staged_app: PathBuf },
    Failed(String),
}

impl fmt::Display for UpdateState {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            UpdateState::UpToDate => write!(f, "up to date"),
            UpdateState::Available(item) => write!(f, "update available: {}", item.version),
            UpdateState::Downloading { downloaded, total } if *total > 0 => {
                write!(f, "downloading update ({downloaded}/{total} bytes)")
            }
            UpdateState::Downloading { downloaded, .. } => {
                write!(f, "downloading update ({downloaded} bytes)")
            }
            UpdateState::ReadyToRelaunch { .. } => write!(f, "update ready -- relaunch to apply"),
            UpdateState::Failed(msg) => write!(f, "update check failed: {msg}"),
        }
    }
}

/// The "check now" entry point: one synchronous check against the
/// running version, collapsed to a [`UpdateState`] (a network/parse
/// error becomes [`UpdateState::Failed`] rather than propagating -- this
/// is meant to feed a UI that shows a state, not handle a `Result`).
#[must_use]
pub fn check_now(appcast_url: &str) -> UpdateState {
    let current = Version::current();
    match check_for_update(appcast_url, &current) {
        Ok(CheckResult::UpToDate) => UpdateState::UpToDate,
        Ok(CheckResult::Available(item)) => UpdateState::Available(item),
        Err(e) => UpdateState::Failed(e.to_string()),
    }
}

/// The interval-based background check entry point. Spawns a thread that
/// calls `on_state` once per `interval` (not immediately -- callers that
/// also want an immediate check should call [`check_now`] once
/// themselves) until `stop` is set to `true`, then exits. `stop` is
/// checked between the sleep and the next check, and the sleep itself is
/// chunked so `stop` takes effect within roughly one second rather than
/// waiting out a whole (potentially long) interval.
pub fn spawn_background_checker(
    appcast_url: String,
    interval: Duration,
    stop: Arc<AtomicBool>,
    mut on_state: impl FnMut(UpdateState) + Send + 'static,
) -> std::thread::JoinHandle<()> {
    std::thread::spawn(move || {
        while !stop.load(Ordering::Relaxed) {
            let mut waited = Duration::ZERO;
            while waited < interval {
                if stop.load(Ordering::Relaxed) {
                    return;
                }
                let chunk = Duration::from_secs(1).min(interval - waited);
                std::thread::sleep(chunk);
                waited += chunk;
            }
            if stop.load(Ordering::Relaxed) {
                return;
            }
            on_state(check_now(&appcast_url));
        }
    })
}


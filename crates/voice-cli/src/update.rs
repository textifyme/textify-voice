// Verifier -- see this module's doc comment for why this calls `ring`.
// ---------------------------------------------------------------------

/// Wraps a 32-byte ed25519 public key and the one operation this whole
/// module exists to gate every install on: does this signature match
/// this exact message under this exact key.
pub struct Verifier {
    public_key: [u8; 32],
}

impl Verifier {
    /// The production constructor: reads [`PUBLIC_KEY_HEX`], the constant
    /// compiled into this binary. Never reads a key from the network, the
    /// appcast, or disk -- see this module's doc comment, point 3.
    pub fn from_compiled_in() -> Result<Self, UpdateError> {
        Self::with_public_key_hex(PUBLIC_KEY_HEX)
    }

    /// Test/tooling constructor: an explicit key, so negative tests
    /// ("signed by the wrong key") can construct a `Verifier` for a key
    /// that is deliberately *not* [`PUBLIC_KEY_HEX`] without needing a
    /// second compiled-in constant.
    pub fn with_public_key_hex(hex: &str) -> Result<Self, UpdateError> {
        Ok(Self {
            public_key: decode_hex_fixed_32(hex, "public key")?,
        })
    }

    /// Verify `signature` (raw 64 bytes) over `message` under this
    /// verifier's public key. `Ok(())` only for an exact match -- ring's
    /// `UnparsedPublicKey::verify` rejects everything else (wrong key,
    /// wrong message, truncated/malformed signature) uniformly as one
    /// opaque `Unspecified` error, which this maps to
    /// [`UpdateError::SignatureInvalid`] rather than trying to distinguish
    /// *why* a forged or corrupted signature failed -- that distinction
    /// is not something a verifier should leak.
    ///
    /// Calls `ring::signature::UnparsedPublicKey::verify` unconditionally --
    /// see this module's doc comment for why `ring` is used here (no safe
    /// substitute exists). Not behind a feature flag: an install-gating
    /// check that can be compiled out is not a check.
    pub fn verify(&self, message: &[u8], signature: &[u8; 64]) -> Result<(), UpdateError> {
        let key =
            ring::signature::UnparsedPublicKey::new(&ring::signature::ED25519, &self.public_key);
        key.verify(message, signature)
            .map_err(|_| UpdateError::SignatureInvalid)
    }
}

